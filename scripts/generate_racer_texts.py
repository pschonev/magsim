"""Generate web/src/utils/racerTexts.ts and racerGlossary.ts from docs/racers.md."""

import json
import re
import unicodedata
from pathlib import Path
from typing import get_args

from magsim.core.types import RacerName

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "docs" / "racers.md"
TARGET = ROOT / "web" / "src" / "utils" / "racerTexts.ts"
GLOSSARY_TARGET = ROOT / "web" / "src" / "utils" / "racerGlossary.ts"
HEADER = "// Generated by scripts/generate_racer_texts.py from docs/racers.md. Do not edit.\n"
CARD_SETS = {
    "Magical Athlete: Second Wind": "Second Wind",
    "Magical Athlete (original game)": "Base game",
}
GLOSSARY_TYPE = (
    "export interface RacerGlossaryEntry {\n"
    "  key: string;\n"
    '  set: "Second Wind" | "Base game";\n'
    "  title: string;\n"
    "  ability: string;\n"
    "  clarifications: string | null;\n"
    "  flavor: string;\n"
    "  implemented: boolean;\n"
    "}\n"
)


def normalize(name: str) -> str:
    plain = unicodedata.normalize("NFKD", name).encode("ascii", "ignore").decode()
    return re.sub(r"[^a-z0-9]", "", plain.lower())


def table_rows() -> list[tuple[str, list[str]]]:
    """Return (card set, cells) for every racer row of docs/racers.md."""
    rows: list[tuple[str, list[str]]] = []
    card_set = ""
    for line in SOURCE.read_text().splitlines():
        if line.startswith("## "):
            card_set = CARD_SETS.get(line[3:].strip(), "")
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) < 4 or cells[0] in ("Name", "Racer", "") or set(cells[0]) <= {"-", " "}:
            continue
        rows.append((card_set, cells))
    return rows


def glossary_entry(card_set: str, cells: list[str], internal: dict[str, str]) -> dict[str, str | bool | None]:
    """One glossary row; racers without an engine module keep their plain name as key."""
    key = internal.get(normalize(cells[0]))
    return {
        "key": key or re.sub(r"[^A-Za-z0-9]", "", cells[0]),
        "set": card_set,
        "title": cells[1],
        "ability": cells[2],
        "clarifications": None if cells[3] == "none" else cells[3],
        "flavor": cells[4],
        "implemented": key is not None,
    }


def main() -> None:
    internal = {normalize(name): name for name in get_args(RacerName)}
    rows = table_rows()
    texts: dict[str, str] = {}
    for _, cells in rows:
        key = internal.get(normalize(cells[0]))
        if key:
            texts[key] = f"{cells[1].title()}: {cells[2]}"
    body = json.dumps(dict(sorted(texts.items())), indent=2, ensure_ascii=False)
    TARGET.write_text(
        HEADER + f"export const RACER_TEXTS: Record<string, string> = {body};\n",
    )
    print(f"{len(texts)} racers written to {TARGET}")

    entries = [glossary_entry(card_set, cells, internal) for card_set, cells in rows if card_set and len(cells) >= 5]
    lines = "\n".join(f"  {json.dumps(entry, ensure_ascii=False)}," for entry in entries)
    GLOSSARY_TARGET.write_text(
        HEADER + GLOSSARY_TYPE + f"\nexport const RACER_GLOSSARY: RacerGlossaryEntry[] = [\n{lines}\n];\n",
    )
    print(f"{len(entries)} glossary entries written to {GLOSSARY_TARGET}")


if __name__ == "__main__":
    main()
