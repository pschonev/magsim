"""Generate web/src/utils/racerTexts.ts (power text per racer) from docs/racers.md."""

import json
import re
import unicodedata
from pathlib import Path
from typing import get_args

from magsim.core.types import RacerName

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "docs" / "racers.md"
TARGET = ROOT / "web" / "src" / "utils" / "racerTexts.ts"


def normalize(name: str) -> str:
    plain = unicodedata.normalize("NFKD", name).encode("ascii", "ignore").decode()
    return re.sub(r"[^a-z0-9]", "", plain.lower())


def main() -> None:
    internal = {normalize(name): name for name in get_args(RacerName)}
    texts: dict[str, str] = {}
    for line in SOURCE.read_text().splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) < 4 or cells[0] in ("Name", "") or set(cells[0]) <= {"-", " "}:
            continue
        key = internal.get(normalize(cells[0]))
        if key:
            texts[key] = f"{cells[1].title()}: {cells[2]}"
    body = json.dumps(dict(sorted(texts.items())), indent=2, ensure_ascii=False)
    TARGET.write_text(
        "// Generated by scripts/generate_racer_texts.py from docs/racers.md. Do not edit.\n"
        f"export const RACER_TEXTS: Record<string, string> = {body};\n",
    )
    print(f"{len(texts)} racers written to {TARGET}")


if __name__ == "__main__":
    main()
